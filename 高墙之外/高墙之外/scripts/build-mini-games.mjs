import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const generatedBanner = "/* Generated by scripts/build-mini-games.mjs from source.js. Do not edit. */\n";

const games = [
  {
    directory: "齿轮校准互动空间",
    kind: "direct"
  },
  {
    directory: "整理图书互动空间",
    kind: "react",
    gameKey: "bookshelf",
    sourceKey: "bookshelf",
    globalApi: "MagicBookshelfGame"
  },
  {
    directory: "地下水管迷宫",
    kind: "react",
    gameKey: "pipeMaze",
    sourceKey: "pipeMaze",
    globalApi: "PipeMazeGame"
  }
];

function normalizeNewlines(value) {
  return value.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n").trimEnd() + "\n";
}

function createReactEntry(game) {
  return `
(function () {
"use strict";
const runtime = window.BeyondWallsReactRuntime;
const source = window.BeyondWallsMiniGameSources && window.BeyondWallsMiniGameSources.${game.sourceKey};
if (!runtime) throw new Error("Missing shared React runtime for ${game.gameKey}");
if (!source) throw new Error("Missing mini-game source: ${game.gameKey}");

window.BeyondWallsMiniGames = window.BeyondWallsMiniGames || {};
window.BeyondWallsMiniGames.${game.gameKey} = {
  mount(rootElement, options) {
    if (!rootElement) throw new Error("Missing mini-game root: ${game.gameKey}");
    source.setMountOptions(options);
    const reactRoot = runtime.ReactDOM.createRoot(rootElement);
    reactRoot.render(runtime.jsxRuntime.jsx(source.Component, {}));
    let destroyed = false;
    return {
      get api() { return source.getApi ? source.getApi() : window.${game.globalApi} || null; },
      destroy() {
        if (destroyed) return;
        destroyed = true;
        reactRoot.unmount();
        source.clearMountOptions();
      }
    };
  }
};
})();
`;
}

let hasDrift = false;
for (const game of games) {
  const sourcePath = path.join(projectRoot, game.directory, "source.js");
  const outputPath = path.join(projectRoot, game.directory, "component.js");
  const source = normalizeNewlines(fs.readFileSync(sourcePath, "utf8"));
  const output = generatedBanner + source + (game.kind === "react" ? createReactEntry(game) : "");
  const current = fs.existsSync(outputPath) ? normalizeNewlines(fs.readFileSync(outputPath, "utf8")) : "";

  if (current === normalizeNewlines(output)) continue;
  if (checkOnly) {
    hasDrift = true;
    console.error(`Generated file is stale: ${path.relative(projectRoot, outputPath)}`);
  } else {
    fs.writeFileSync(outputPath, normalizeNewlines(output), "utf8");
    console.log(`Built ${path.relative(projectRoot, outputPath)}`);
  }
}

const indexPath = path.join(projectRoot, "index.html");
const indexSource = fs.readFileSync(indexPath, "utf8");
const versionMatch = indexSource.match(/BeyondWallsAssetVersion\s*=\s*"([^"]+)"/);
if (!versionMatch) throw new Error("index.html must declare window.BeyondWallsAssetVersion");
const releaseVersion = versionMatch[1];
const versionedIndex = indexSource.replace(
  /(<script\s+src="[^"?]+)(?:\?v=[^"]*)?("><\/script>)/g,
  `$1?v=${releaseVersion}$2`
);
if (versionedIndex !== indexSource) {
  if (checkOnly) {
    hasDrift = true;
    console.error("Script asset versions in index.html are stale");
  } else {
    fs.writeFileSync(indexPath, versionedIndex, "utf8");
    console.log(`Synced script asset version ${releaseVersion} in index.html`);
  }
}

if (hasDrift) process.exitCode = 1;
